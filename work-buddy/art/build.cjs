// Builds hooks/art.ts from the three SVGs in this folder (each wraps a PNG).
// Run: node art/build.cjs   (needs the `sharp` package resolvable, e.g. NODE_PATH)
const fs = require('fs')
const path = require('path')
const sharp = require('sharp')

const DIR = __dirname
const OUT = path.join(DIR, '..', 'hooks', 'art.ts')
const MODES = { working: 'claude-working.svg', waiting: 'claude-waiting.svg', resting: 'claude-sleeping.svg' }
const DESKTOP_WIDTH = 200 // px of the picture embedded for the desktop app
const TERMINAL_HEIGHT = 48 // px kept for the terminal's pixel art

async function one(file) {
  const svg = fs.readFileSync(path.join(DIR, file), 'utf8')
  const style = (svg.match(/<style>([\s\S]*?)<\/style>/) || [, ''])[1].trim()
  const png = Buffer.from(svg.match(/base64,([A-Za-z0-9+/=\s]+)/)[1].replace(/\s/g, ''), 'base64')
  const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  const { width: W, height: H } = info
  const opaque = (x, y) => data[(y * W + x) * 4 + 3] > 24
  // Runs of rows holding anything: the character first, the status pill last.
  const runs = []
  for (let y = 0, inRun = false; y < H; y++) {
    let any = false
    for (let x = 0; x < W && !any; x++) any = opaque(x, y)
    if (any && !inRun) runs.push([y, y]), (inRun = true)
    else if (any) runs[runs.length - 1][1] = y
    else inRun = false
  }
  const big = runs.filter(([a, b]) => b - a > 6)
  const cols = (top, bottom) => {
    let l = W, r = 0
    for (let y = top; y <= bottom; y++) for (let x = 0; x < W; x++) if (opaque(x, y)) (l = Math.min(l, x)), (r = Math.max(r, x))
    return [l, r]
  }
  const top = big[0][0], bottom = big[big.length - 1][1]
  const charBottom = big.length > 1 ? big[big.length - 2][1] : bottom
  const pad = 6
  const box = (t, b) => {
    const [l, r] = cols(t, b)
    const left = Math.max(0, l - pad), y = Math.max(0, t - pad)
    return { left, top: y, width: Math.min(W, r + pad) - left, height: Math.min(H, b + pad) - y }
  }
  // Desktop: character and pill, as a small palette PNG inside an SVG.
  const d = box(top, bottom)
  const small = await sharp(png).extract(d).resize({ width: DESKTOP_WIDTH }).png({ palette: true, quality: 85, compressionLevel: 9 }).toBuffer()
  const h = Math.round((d.height * DESKTOP_WIDTH) / d.width)
  const desktop = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${DESKTOP_WIDTH} ${h}" width="${DESKTOP_WIDTH}" height="${h}"><style>${style.replace(/\s+/g, ' ')}</style><image class="mascot" x="0" y="0" width="${DESKTOP_WIDTH}" height="${h}" href="data:image/png;base64,${small.toString('base64')}"/></svg>`
  // Terminal: the character alone, as RGBA pixels the module scales to the rows it has.
  const t = box(top, charBottom)
  const px = await sharp(png).extract(t).resize({ height: TERMINAL_HEIGHT, kernel: 'lanczos3' }).ensureAlpha().raw().toBuffer({ resolveWithObject: true })
  return { desktop, desktopWidth: DESKTOP_WIDTH, desktopHeight: h, terminal: { width: px.info.width, height: px.info.height, rgba: px.data.toString('base64') } }
}

;(async () => {
  const out = {}
  for (const [mode, file] of Object.entries(MODES)) {
    out[mode] = await one(file)
    console.log(mode, 'desktop svg', out[mode].desktop.length, 'chars; terminal', out[mode].terminal.width + 'x' + out[mode].terminal.height)
  }
  fs.writeFileSync(OUT, `// Generated by art/build.cjs from art/*.svg: do not edit by hand.\n\nexport type Art = {\n  desktop: string\n  desktopWidth: number\n  desktopHeight: number\n  terminal: { width: number; height: number; rgba: string }\n}\n\nexport const ART: Record<'working' | 'waiting' | 'resting', Art> = ${JSON.stringify(out, null, 2)}\n`)
  console.log('wrote', OUT, fs.statSync(OUT).size, 'bytes')
})()
